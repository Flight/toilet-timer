#!/usr/bin/env python3
"""
Convert a fixed-cell BDF font into a C bitmap font table.

Each glyph is emitted as FONT_HEIGHT rows of uint16_t; bit 15 is the
left-most pixel column of the cell.

Usage:
    python3 bdf2font.py 10x20.bdf font_10x20.c
    python3 bdf2font.py 10x20.bdf --preview "Сьогодні 12"
"""

import argparse
import sys

ASCII_RANGE = range(32, 127)
EXTRA_CODEPOINTS = (
    [0x00B0]                             # ° (degree sign)
    + list(range(0x0410, 0x0450))        # А..я
    + [0x0401, 0x0451]                   # Ё ё
    + [0x0404, 0x0454, 0x0406, 0x0456]   # Є є І і
    + [0x0407, 0x0457, 0x0490, 0x0491]   # Ї ї Ґ ґ
)


def parse_bdf(path):
    glyphs = {}
    props = {}
    with open(path, "r", encoding="latin-1") as f:
        lines = f.read().splitlines()

    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("FONTBOUNDINGBOX"):
            _, w, h, xo, yo = line.split()
            props["bbox"] = (int(w), int(h), int(xo), int(yo))
        elif line.startswith("FONT_ASCENT"):
            props["ascent"] = int(line.split()[1])
        elif line.startswith("FONT_DESCENT"):
            props["descent"] = int(line.split()[1])
        elif line.startswith("STARTCHAR"):
            enc = None
            bbx = None
            rows = []
            i += 1
            while not lines[i].startswith("ENDCHAR"):
                l = lines[i]
                if l.startswith("ENCODING"):
                    enc = int(l.split()[1])
                elif l.startswith("BBX"):
                    _, w, h, xo, yo = l.split()
                    bbx = (int(w), int(h), int(xo), int(yo))
                elif l.startswith("BITMAP"):
                    i += 1
                    while not lines[i].startswith("ENDCHAR"):
                        rows.append(lines[i].strip())
                        i += 1
                    i -= 1
                i += 1
            if enc is not None and enc >= 0:
                glyphs[enc] = (bbx, rows)
        i += 1
    return props, glyphs


def render_cell(props, glyph):
    """Return list of FONT_HEIGHT ints (16-bit, bit15 = column 0)."""
    cell_w, cell_h, _, _ = props["bbox"]
    ascent = props["ascent"]
    bbx, rows = glyph
    w, h, xoff, yoff = bbx
    cell = [0] * cell_h
    for idx, hexrow in enumerate(rows):
        nbits = len(hexrow) * 4
        value = int(hexrow, 16) << (16 - nbits)   # left-align to 16 bits
        if xoff >= 0:
            value >>= xoff
        else:
            value = (value << -xoff) & 0xFFFF
        row = ascent - yoff - h + idx
        if 0 <= row < cell_h:
            cell[row] |= value & 0xFFFF
    return cell


def c_name(cp):
    ch = chr(cp)
    if cp < 127 and ch not in ("\\", "'", "*", "/"):
        return "'%s' (%d)" % (ch, cp)
    return "U+%04X %s" % (cp, ch if cp >= 127 else "")


def emit_c(props, glyphs, out, src_name):
    cell_w, cell_h, _, _ = props["bbox"]
    w = out.write
    w("/**\n * @file font_%dx%d.c\n" % (cell_w, cell_h))
    w(" * @brief %dx%d bitmap font data\n" % (cell_w, cell_h))
    w(" *\n * Generated by tools/bdf2font.py from %s (X11 Misc-Fixed family).\n" % src_name)
    w(" * Public domain font. Share and enjoy.\n *\n")
    w(" * Each glyph is %d rows of uint16_t; bit 15 is the left-most pixel.\n */\n\n" % cell_h)
    w('#include "font_%dx%d.h"\n\n' % (cell_w, cell_h))

    w("const uint16_t font_%dx%d_ascii[%d][%d] = {\n" % (cell_w, cell_h, len(ASCII_RANGE), cell_h))
    for cp in ASCII_RANGE:
        cell = render_cell(props, glyphs[cp])
        w("    {" + ", ".join("0x%04X" % v for v in cell) + "}, /* %s */\n" % c_name(cp))
    w("};\n\n")

    w("const font_glyph_%dx%d_t font_%dx%d_extra[] = {\n" % (cell_w, cell_h, cell_w, cell_h))
    for cp in EXTRA_CODEPOINTS:
        if cp not in glyphs:
            print("WARNING: U+%04X missing in font" % cp, file=sys.stderr)
            continue
        cell = render_cell(props, glyphs[cp])
        w("    {0x%04X, {" % cp + ", ".join("0x%04X" % v for v in cell) + "}}, /* %s */\n" % c_name(cp))
    w("};\n\n")
    w("const size_t font_%dx%d_extra_count = sizeof(font_%dx%d_extra) / sizeof(font_%dx%d_extra[0]);\n"
      % (cell_w, cell_h, cell_w, cell_h, cell_w, cell_h))


def preview(props, glyphs, text):
    cell_w, cell_h, _, _ = props["bbox"]
    cells = [render_cell(props, glyphs[ord(c)]) for c in text]
    for r in range(cell_h):
        line = ""
        for cell in cells:
            line += "".join("#" if cell[r] & (0x8000 >> c) else "." for c in range(cell_w)) + " "
        print(line)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("bdf")
    ap.add_argument("output", nargs="?")
    ap.add_argument("--preview")
    args = ap.parse_args()

    props, glyphs = parse_bdf(args.bdf)
    if args.preview:
        preview(props, glyphs, args.preview)
        return
    if not args.output:
        ap.error("output file required")
    with open(args.output, "w", encoding="utf-8") as out:
        emit_c(props, glyphs, out, args.bdf.split("/")[-1])
    print("wrote %s (%d ascii + %d extra glyphs)" % (args.output, len(ASCII_RANGE), len(EXTRA_CODEPOINTS)))


if __name__ == "__main__":
    main()
